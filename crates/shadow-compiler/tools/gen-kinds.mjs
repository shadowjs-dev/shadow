#!/usr/bin/env node
/**
 * Generates `src/kinds.rs`: the match that stores an arena index in the `node_id` cell of any `AstKind`
 * of oxc_ast. The list of variants is read from the oxc_ast source in the cargo registry, so the file
 * is regenerated whenever the oxc version changes. Run from the repository root:
 * `node crates/shadow-compiler/tools/gen-kinds.mjs`.
 */
import { execFileSync } from "node:child_process";
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const metadata = JSON.parse(
  execFileSync("cargo", ["metadata", "--format-version", "1", "--locked"], {
    cwd: join(here, ".."),
    encoding: "utf8",
    maxBuffer: 1 << 28,
  }),
);
const pkg = metadata.packages.find((p) => p.name === "oxc_ast");
if (pkg === undefined) throw new Error("oxc_ast is not in the dependency graph");
const source = readFileSync(join(dirname(pkg.manifest_path), "src/generated/ast_kind.rs"), "utf8");
const body = /pub enum AstKind<'a> \{([\s\S]*?)\n\}/.exec(source);
if (body === null) throw new Error("AstKind enum not found");
const variants = [...body[1].matchAll(/^\s{4}(\w+)\(&'a/gm)].map((m) => m[1]);
if (variants.length < 150) throw new Error(`too few variants: ${variants.length}`);

const arms = variants
  .map((name) => `        AstKind::${name}(node) => node.set_node_id(id),`)
  .join("\n");
const out = `//! Generated by tools/gen-kinds.mjs from oxc_ast ${pkg.version}. Do not edit.

use oxc_ast::ast_kind::AstKind;
use oxc_syntax::node::NodeId;

/// Stores \`id\` in the \`node_id\` cell of the node \`kind\` points at.
pub(crate) fn set_node_id(kind: AstKind<'_>, id: NodeId) {
    match kind {
${arms}
    }
}
`;
writeFileSync(join(here, "../src/kinds.rs"), out);
console.log(`wrote ${variants.length} variants for oxc_ast ${pkg.version}`);
